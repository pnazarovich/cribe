import AppKit
import OSLog

/// Общий рецепт окна HUD: и пилюля, и карточки обязаны появляться поверх ЧУЖОГО
/// полноэкранного пространства — там пользователь и живёт.
///
/// Рецепт проверен пробой на живой системе (2026-08-02, полноэкранные Chrome, cmux и
/// Claude): семь сочетаний яруса и поведения — `.statusBar`, `.screenSaver`, `.popUpMenu`,
/// щит минус один, с `.stationary` и без, `.moveToActiveSpace` вместо `.canJoinAllSpaces` —
/// показываются над полным экраном ОДИНАКОВО хорошо. То есть дело было не в рецепте.
///
/// Дело было в том, что рецепт со временем перестаёт действовать. Замерено на боевом
/// процессе, прожившем сорок минут: во время живой записи окно пилюли (ярус 25, тот самый
/// `collectionBehavior`) не появлялось ни на одном полноэкранном пространстве, оставаясь
/// на рабочем столе, и ехало вместе с переключением пространств — то есть вело себя как
/// окно, ПРИВЯЗАННОЕ к пространству. Свежий процесс той же сборки в тот же момент
/// показывал ту же панель поверх того же полного экрана без единой осечки.
///
/// Подтверждение заявки на каждом показе — первое, что из этого вышло, — не помогло.
/// Замер 2026-08-08 на процессе, прожившем шесть часов: сначала семь диктовок подряд
/// показались чисто, а с 01:06:57 КАЖДЫЙ показ заставал окно вне активного пространства —
/// одиннадцать раз подряд, и переподанная заявка не вернула его ни разу. Между показами
/// окно успевало уйти с экрана и вернуться (`orderOut` на скрытии, `orderFront` на показе),
/// то есть дело и не в том, что заявку меняют на видимом окне.
///
/// Что при этом работало: карточки, которые строят себе НОВОЕ окно на каждый показ, и
/// свежий процесс. Отсюда вывод: стареет не рецепт и не процесс, а само окно — прописку
/// теряет конкретный экземпляр, и вернуть её на нём нечем.
///
/// Отсюда правило: окно HUD живёт ровно один показ. Содержимое переезжает в свежую
/// оболочку (`renew`), и прописку та получает при рождении — тем же путём, каким её
/// получают карточки, на которые жалоб не было.
@MainActor
enum HUDWindow {
    /// Ярус HUD: `.floating` (3) перекрывается полноэкранным видео и презентациями,
    /// `.statusBar` (25) — нет.
    static let level: NSWindow.Level = .statusBar

    /// `.canJoinAllSpaces` — окно на всех пространствах, включая чужие полноэкранные;
    /// `.fullScreenAuxiliary` — разрешение показываться рядом с полноэкранным окном.
    static let spaceBehavior: NSWindow.CollectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]

    private static let logger = Logger(subsystem: "online.nazarovych.cribe", category: "Panel")

    /// Показ. `extra` — добавка к общему поведению (пилюля просит ещё `.stationary`,
    /// чтобы не разъезжаться с окнами на Mission Control).
    ///
    /// Именно `orderFrontRegardless`: `makeKey` увёл бы фокус с целевого поля ввода.
    ///
    /// Следом — проверка, и только проверка: чинить показ на месте нечем, а знать, что
    /// человек его не увидел, надо. Пока окно свежее, строки в логе быть не должно.
    static func orderFront(_ window: NSWindow, extra: NSWindow.CollectionBehavior = []) {
        window.collectionBehavior = spaceBehavior.union(extra)
        window.orderFrontRegardless()
        Task { @MainActor in
            guard window.isVisible, !window.isOnActiveSpace else { return }
            logger.notice("Окно HUD не попало на активное пространство — показ прошёл впустую")
        }
    }

    /// Свежая оболочка вместо прежней: содержимое и место переезжают как есть, меняется
    /// только окно. Так HUD получает прописку во всех пространствах заново — единственным
    /// способом, который на практике не отказывает.
    ///
    /// Дерево SwiftUI не пересобирается: переезжает уже отрисованный `contentView`, и
    /// анимация появления начинается с того же кадра, что и раньше.
    static func renew<Panel: NSWindow>(_ old: Panel, make: () -> Panel) -> Panel {
        let fresh = make()
        fresh.setFrame(old.frame, display: false)
        fresh.contentView = old.contentView
        old.orderOut(nil)
        return fresh
    }
}
