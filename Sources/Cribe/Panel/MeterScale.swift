import CoreGraphics
import Foundation

/// Шкала индикатора громкости: из RMS звука в долю высоты столбика.
///
/// Шкала самонастраивающаяся, и это не украшательство. Фиксированные пороги в децибелах
/// не годятся: у каждого микрофона своя чувствительность, у каждой комнаты своя тишина, а
/// системная громкость входа — ползунок, который человек двигает как хочет. Замер по
/// записям владельца целиком (238 кадров, перцентили): тишина −44 dBFS, обычная речь −28,
/// пики −20 — то есть размах чуть больше двадцати децибел.
///
/// Границы двигаются **медленно и несимметрично**, и это главное. Первая попытка считала
/// их перцентилями по окну в пять секунд, пересчитывая каждый кадр: на улице, где шум
/// гуляет, границы прыгали вместе с ним, а с ними прыгала вся лента. Теперь пол и потолок
/// ползут с постоянной времени в секунды, и мелкий шум их не двигает вовсе.
struct MeterRange {
    /// Наименьший размах шкалы — и он же тот самый размах, что намерян на живой речи.
    ///
    /// Было четырнадцать, и это и есть причина жалобы «всё на максимуме»: настоящее
    /// расстояние от тишины комнаты до пиков голоса — двадцать с лишним децибел, и на
    /// четырнадцати обычная речь оказывалась выше потолка, то есть у верхнего края.
    /// Двадцать оставляют верх шкалы под пики, а обычной речи — середину.
    static let minimumSpan: Float = 20

    /// Пол — уровень тишины. Вниз идёт быстро: стало тише — это видно сразу.
    /// Вверх ползёт очень медленно: иначе собственная речь поднимала бы «тишину» до своего
    /// уровня, и ряд оседал бы прямо во время фразы. На прежнем значении пол уходил за
    /// громкой речью почти на четыре децибела в секунду — на длинной диктовке столбики
    /// заметно проседали к концу.
    private static let floorFall: Float = 0.25
    private static let floorRise: Float = 0.008

    /// Потолок — уровень громкой речи. За пиком тянется почти мгновенно, оседает медленно.
    /// Мгновенно — потому что отстающий потолок и есть залипание на максимуме: пока он
    /// догоняет, всё, что выше него, показывается одинаковой полной высотой.
    private static let ceilingRise: Float = 0.9
    private static let ceilingFall: Float = 0.01

    /// Сглаживание **несимметрично** — так устроены все настоящие индикаторы громкости.
    /// Вверх высота идёт почти мгновенно: начало слова обязано отзываться сразу, иначе ряд
    /// выглядит вялым и отстаёт от речи. Вниз опускается медленно: спад и есть то, что
    /// превращает дрожь отдельных замеров в плавное движение.
    private static let attack: CGFloat = 0.75
    private static let release: CGFloat = 0.18

    private(set) var floor: Float = -55
    private(set) var ceiling: Float = -25
    private var smoothed: CGFloat = 0
    /// Сколько первых замеров уходит на калибровку. Они не показываются вовсе: пока
    /// границы неизвестны, показывать нечего.
    ///
    /// Пять, а не три, и берётся **медиана**. Замер по настоящим записям владельца: старт
    /// сессии даёт первый кадр около −50 dBFS, второй — пустой буфер (−98…−115), и лишь с
    /// третьего идёт шум комнаты (−36…−44). И минимум, и первый кадр промахиваются мимо
    /// комнаты; на минимуме шкала уезжала так, что обычный шум оказывался выше потолка, и
    /// ряд вспыхивал на максимум на первые полсекунды. Медиана из пяти переживает и провал,
    /// и щелчок: чтобы сбить её, нужно три испорченных кадра подряд.
    private static let warmupFrames = 5
    private var warmup: [Float] = []

    /// Принимает очередной замер и отдаёт готовую высоту для него.
    ///
    /// Высота считается **здесь и сейчас** и дальше не пересчитывается: лента хранит уже
    /// посчитанные высоты, а не уровни. Иначе сдвиг границ перерисовывал бы разом все
    /// столбики, включая нарисованные секунду назад, — ровно та пляска, на которую
    /// жаловался владелец.
    mutating func push(_ level: Float) -> CGFloat {
        guard level > 0 else { return 0 }
        let decibels = 20 * log10(level)

        // Пока идёт калибровка, наружу отдаём ноль: показывать нечего, границы неизвестны.
        if warmup.count < Self.warmupFrames {
            warmup.append(decibels)
            if warmup.count == Self.warmupFrames {
                // Середина, а не край: и пустой буфер, и щелчок — это края.
                floor = warmup.sorted()[Self.warmupFrames / 2] - 2
                ceiling = floor + Self.minimumSpan
            }
            return 0
        }

        floor += (decibels - floor) * (decibels < floor ? Self.floorFall : Self.floorRise)
        ceiling += (decibels - ceiling) * (decibels > ceiling ? Self.ceilingRise : Self.ceilingFall)
        // Потолок не имеет права опуститься к полу: шкала обязана остаться шкалой.
        ceiling = max(ceiling, floor + Self.minimumSpan)

        let span = max(Self.minimumSpan, ceiling - floor)
        let raw = CGFloat(min(1, max(0, (decibels - floor) / span)))
        smoothed += (raw - smoothed) * (raw > smoothed ? Self.attack : Self.release)
        return smoothed
    }
}
