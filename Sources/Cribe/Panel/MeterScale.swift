import CoreGraphics
import Foundation

/// Шкала индикатора громкости: из RMS звука в долю высоты столбика.
///
/// Шкала самонастраивающаяся, и это не украшательство. Фиксированные пороги в децибелах
/// не годятся: у каждого микрофона своя чувствительность, у каждой комнаты свой шум, а
/// системная громкость входа — ползунок, который человек двигает как хочет. Замер на
/// записях владельца: тишина −38 dBFS, речь −33, пики −25, весь размах тринадцать децибел.
/// На фиксированной шкале −55…−12 такая тишина приходилась на четверть высоты.
///
/// Границы двигаются **медленно и несимметрично**, и это главное. Первая попытка считала
/// их перцентилями по окну в пять секунд, пересчитывая каждый кадр: на улице, где шум
/// гуляет, границы прыгали вместе с ним, а с ними прыгала вся лента. Теперь пол и потолок
/// ползут с постоянной времени в секунды, и мелкий шум их не двигает вовсе.
struct MeterRange {
    /// Наименьший размах шкалы. Без него в полной тишине разница между «чуть тише»
    /// и «чуть громче» растянулась бы на всю высоту, и ряд плясал бы от шороха.
    static let minimumSpan: Float = 14

    /// Пол — уровень тишины. Вниз идёт быстро: стало тише — это видно сразу.
    /// Вверх ползёт медленно, около десяти секунд: иначе собственная речь поднимала бы
    /// «тишину» до своего уровня, и ряд оседал бы прямо во время фразы.
    private static let floorFall: Float = 0.25
    private static let floorRise: Float = 0.015

    /// Потолок — уровень громкой речи. За пиком тянется быстро, оседает медленно:
    /// от этого зависит только запас сверху, и дёргать его незачем.
    private static let ceilingRise: Float = 0.3
    private static let ceilingFall: Float = 0.01

    /// Сглаживание **несимметрично** — так устроены все настоящие индикаторы громкости.
    /// Вверх высота идёт почти мгновенно: начало слова обязано отзываться сразу, иначе ряд
    /// выглядит вялым и отстаёт от речи. Вниз опускается медленно: спад и есть то, что
    /// превращает дрожь отдельных замеров в плавное движение.
    private static let attack: CGFloat = 0.75
    private static let release: CGFloat = 0.18

    private(set) var floor: Float = -55
    private(set) var ceiling: Float = -25
    private var smoothed: CGFloat = 0

    /// Принимает очередной замер и отдаёт готовую высоту для него.
    ///
    /// Высота считается **здесь и сейчас** и дальше не пересчитывается: лента хранит уже
    /// посчитанные высоты, а не уровни. Иначе сдвиг границ перерисовывал бы разом все
    /// столбики, включая нарисованные секунду назад, — ровно та пляска, на которую
    /// жаловался владелец.
    mutating func push(_ level: Float) -> CGFloat {
        guard level > 0 else { return 0 }
        let decibels = 20 * log10(level)

        floor += (decibels - floor) * (decibels < floor ? Self.floorFall : Self.floorRise)
        ceiling += (decibels - ceiling) * (decibels > ceiling ? Self.ceilingRise : Self.ceilingFall)
        // Потолок не имеет права опуститься к полу: шкала обязана остаться шкалой.
        ceiling = max(ceiling, floor + Self.minimumSpan)

        let span = max(Self.minimumSpan, ceiling - floor)
        let raw = CGFloat(min(1, max(0, (decibels - floor) / span)))
        smoothed += (raw - smoothed) * (raw > smoothed ? Self.attack : Self.release)
        return smoothed
    }
}
