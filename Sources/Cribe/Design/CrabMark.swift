import AppKit
import SwiftUI

/// Краб — тот самый рисунок, что и на иконке приложения, без фона.
///
/// Именно рисунок, а не перерисовка: узнаваемость держится на полосах эквалайзера вместо
/// клешней, и любое упрощение первым делом съедает как раз их. Поэтому в интерфейсе краб
/// живёт только там, где ему хватает места — примерно от 24 pt. В строке состояния (18 pt)
/// он превращается в тёмную крапину, и там остаётся системный значок волны.
///
/// Файл лежит в ресурсах бандла и кладётся туда сборкой (`scripts/build-app.sh`), а не через
/// ресурсы SwiftPM: приложение и так собирается xcodebuild-ом со своим списком ресурсов.
/// Если картинки почему-то нет (запуск из тестов, чужая сборка) — показываем волну, как
/// показывали раньше, а не пустоту.
struct CrabMark: View {
    var size: CGFloat = 28

    var body: some View {
        if let image = NSImage(named: "CrabMark") {
            Image(nsImage: image)
                .resizable()
                .scaledToFit()
                .frame(width: size, height: size)
                .accessibilityLabel("Cribe")
        } else {
            Image(systemName: "waveform")
                .font(.system(size: size * 0.8))
        }
    }
}
