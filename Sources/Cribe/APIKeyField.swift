import Foundation

/// Решение автосохранения ключа OpenAI: менялось значение или нет.
///
/// Вынесено из вью ради одного случая, который дорого стоит и который иначе не проверить:
/// если связка ключей не отдала ключ, поле окажется пустым при живом ключе внутри. Пустое
/// поле по закрытии окна означало бы «удалить» — и приложение стёрло бы то, что не смогло
/// прочитать. Поэтому сравниваем с тем, что прочитали, а не с пустотой.
enum APIKeyField {
    /// Стоит ли писать в связку. Пробелы по краям не считаются правкой: ключ всё равно
    /// сохраняется обрезанным, и без этого уход фокуса переписывал бы его без нужды.
    static func changed(typed: String, stored: String) -> Bool {
        typed.trimmingCharacters(in: .whitespacesAndNewlines)
            != stored.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}
