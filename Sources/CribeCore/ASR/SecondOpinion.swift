import Foundation

/// Второе мнение о куске речи: не сказан ли он на соседнем языке.
///
/// **Откуда взялось.** Whisper декодирует окно с ОДНИМ языковым токеном. Украинская фраза
/// внутри русской диктовки поэтому выходит не украинской и даже не русской, а фонетическим
/// мусором: «Якщо ви не натискали кнопку входу — не підтверджуйте» превратилось в
/// «он отыскал и кнопку входа у Nepetwarjoita» (живая запись владельца, 2026-08-08).
/// Тот же кусок, вырезанный отдельно и распознанный украинской моделью, читается дословно
/// верно — значит звук чистый, а губит его русский контекст в том же окне декодера.
///
/// **Почему не подсказкой.** Образец смешанной речи в `initial_prompt` уже пробовали и сняли
/// (коммит 441156a): на живой речи он не подсказывал, а переключал язык всей записи. Замер
/// повторён независимо на этой записи — нейтральное двуязычное примечание не меняет ничего.
/// Здесь промпт не трогается вовсе: решение принимается по звуку и покусочно.
///
/// **Числа не на глаз.** Замерены на трёх настоящих записях владельца — синтетическая речь
/// для этой задачи негодна: на ней фича дважды «чинилась» ложно (см. коммит 441156a).
/// Итог проверки: текст и сколько фраз в нём перечитано на соседнем языке.
///
/// Счётчик нужен не для отчётности. Замена молчаливая опаснее сломанного распознавания:
/// «Nepetwarjoita» человек видит и переговаривает, а гладкую украинскую фразу — принимает
/// на веру, даже если модель потеряла в ней отрицание. Поэтому конвейер обязан сказать
/// о замене вслух.
public struct NeighbourPass: Equatable, Sendable {
    public let text: String
    public let replaced: Int

    public init(text: String, replaced: Int) {
        self.text = text
        self.replaced = replaced
    }
}

public enum SecondOpinion {

    /// Уверенность определения языка, ниже которой кусок считается подозрительным.
    /// Это натуральный логарифм вероятности: −0.10 ≈ 90 %.
    ///
    /// Замер на боевом пути (запись обрезана по тишине, разметка — проходом без подсказки):
    /// чистые русские фразы дают −0.000, −0.001, −0.001; фраза, в которой русское начало
    /// переходит в украинскую вставку, — −0.183. Между ними два порядка, и порог стоит
    /// посередине. Ложное подозрение стоит только времени: заменить текст оно не может,
    /// это решает `prefersNeighbour`.
    public static let suspicion: Float = -0.10

    /// Куски короче не проверяем. На односекундном «Пока.» определение языка соврало
    /// (en, −0.300) — то есть дало ложное подозрение, — а стоит проверка столько же,
    /// сколько на длинном: определение всегда добивает отрезок до тридцати секунд.
    public static let minimumDuration: Double = 1.2

    /// Насколько уверенным должен быть решающий вердикт. Без этого порога голый argmax
    /// уравнивал бы «uk, −0.107» и «uk, −2.0»: назвать сосед может что угодно, если речь
    /// он разобрал плохо. Замер один (−0.107), поэтому порог поставлен заведомо мягким —
    /// он отсекает только откровенную неуверенность.
    public static let verdictFloor: Float = -0.5

    /// Поля вокруг куска для второго прохода. Без них большая модель на коротком отрезке
    /// молча возвращает пустоту: тот же кусок без полей — пусто, с полями —
    /// «Якщо вони натискали кнопку входу - не підтверджуйте».
    public static let padding: Double = 0.3

    /// Стоит ли спрашивать второе мнение об этом куске.
    public static func isSuspicious(confidence: Float, duration: Double) -> Bool {
        duration >= minimumDuration && confidence < suspicion
    }

    /// Забирает ли соседний язык этот кусок себе.
    ///
    /// Решает вердикт сильной модели, а не сравнение уверенностей. Сравнение уверенностей
    /// пробовали, и оно проваливается по неожиданной причине: большая модель, получив
    /// украинскую фразу в отдельности и заданный русский язык, не пишет мусор — она
    /// ПЕРЕВОДИТ («Если вы нажали кнопку входа, то не подтверждайте», −0.150) и делает это
    /// увереннее, чем читает по-украински (−0.194). По уверенности выигрывает перевод,
    /// а человеку нужен оригинал.
    ///
    /// Зато та же модель на том же куске прямо называет язык: uk, −0.107. Два независимых
    /// определителя — дешёвый сомневается, сильный называет соседа — и есть решение.
    public static func belongsToNeighbour(
        verdict: String,
        confidence: Float,
        neighbour: Language,
        reading: String
    ) -> Bool {
        // Пустая расшифровка — провал декодера, а не ответ. Менять на неё живую речь нельзя
        // ни при каком вердикте: большая модель на коротком отрезке отдаёт пустоту молча.
        guard !reading.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return false }
        return verdict == neighbour.rawValue && confidence >= verdictFloor
    }
}
