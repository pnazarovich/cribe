import Foundation

/// Второе мнение о куске речи: не сказан ли он на соседнем языке.
///
/// **Откуда взялось.** Whisper декодирует окно с ОДНИМ языковым токеном. Украинская фраза
/// внутри русской диктовки поэтому выходит не украинской и даже не русской, а фонетическим
/// мусором: «Якщо ви не натискали кнопку входу — не підтверджуйте» превратилось в
/// «он отыскал и кнопку входа у Nepetwarjoita» (живая запись владельца, 2026-08-08).
/// Тот же кусок, вырезанный отдельно и распознанный украинской моделью, читается дословно
/// верно — значит звук чистый, а губит его русский контекст в том же окне декодера.
///
/// **Почему не подсказкой.** Образец смешанной речи в `initial_prompt` уже пробовали и сняли
/// (коммит 441156a): на живой речи он не подсказывал, а переключал язык всей записи. Замер
/// повторён независимо на этой записи — нейтральное двуязычное примечание не меняет ничего.
/// Здесь промпт не трогается вовсе: решение принимается по звуку и покусочно.
///
/// **Числа не на глаз.** Замерено на двенадцати надиктованных владельцем записях
/// (2026-08-08, восемнадцать кусков речи) — синтетическая речь для этой задачи негодна:
/// на ней фича дважды «чинилась» ложно (см. коммит 441156a).

/// Итог проверки: текст и сколько фраз в нём перечитано на соседнем языке.
///
/// Счётчик нужен не для отчётности. Замена молчаливая опаснее сломанного распознавания:
/// «Nepetwarjoita» человек видит и переговаривает, а гладкую украинскую фразу — принимает
/// на веру, даже если модель потеряла в ней отрицание. Поэтому конвейер обязан сказать
/// о замене вслух.
public struct NeighbourPass: Equatable, Sendable {
    public let text: String
    /// Перечитанные фразы — в том виде, в каком они теперь стоят в тексте. Именно их
    /// и называет предупреждение: человеку нужен адрес, а не счёт. Считать по этому же
    /// массиву, отдельного числа не держим.
    public let phrases: [String]

    public var replaced: Int { phrases.count }

    public init(text: String, phrases: [String] = []) {
        self.text = text
        self.phrases = phrases
    }
}

public enum SecondOpinion {

    /// Уверенным считается вердикт не хуже этого. Натуральный логарифм вероятности:
    /// −0.10 ≈ 90 %.
    ///
    /// Замер по восемнадцати кускам речи. Чисто русские куски определитель называет
    /// русскими с уверенностью от −0.000 до −0.003 — то есть безоговорочно. Куски,
    /// которые надо перечитать, лежат далеко по другую сторону: −0.183, −0.556, −1.346,
    /// либо прямо названы украинскими. Между этими областями пусто, и порог стоит в этой
    /// пустоте. Тем же числом меряется и вердикт сильной модели: на чистых кусках она
    /// говорит «русский» с −0.002…−0.007, а на спорном — «русский», но лишь на −0.399.
    public static let certainty: Float = -0.10

    /// Куски короче не проверяем. На односекундном «Пока.» определение языка соврало
    /// (en, −0.300) — то есть дало ложное подозрение, — а стоит проверка столько же,
    /// сколько на длинном: определение всегда добивает отрезок до тридцати секунд.
    public static let minimumDuration: Double = 1.2

    /// Поля вокруг куска для второго прохода. Без них большая модель на коротком отрезке
    /// молча возвращает пустоту: тот же кусок без полей — пусто, с полями —
    /// «Якщо вони натискали кнопку входу - не підтверджуйте».
    public static let padding: Double = 0.3

    /// Стоит ли спрашивать второе мнение об этом куске.
    ///
    /// Поводов два, и первый я поначалу упустил. Определитель языка вовсе не обязан
    /// сомневаться на чужой речи — на половине замеров он уверенно и правильно называл
    /// украинский (−0.006, −0.007, −0.010), и правило «спрашиваем, когда он не уверен»
    /// эти куски молча пропускало. Второй повод — та самая неуверенность: когда русское
    /// начало переходит в украинскую вставку, определитель отвечает «русский», но плохо
    /// (−0.183, −0.556, −1.346).
    public static func isSuspicious(
        detected: String,
        confidence: Float,
        own: Language,
        duration: Double
    ) -> Bool {
        guard duration >= minimumDuration else { return false }
        return detected != own.rawValue || confidence < certainty
    }

    /// Может ли модель соседа отменить замену.
    ///
    /// Право вето, а не право голоса, и разница существенная. Голосом она уже побывала —
    /// и провалилась: на куске, где русское начало переходит в украинскую фразу, она
    /// называет «русский» (−0.399), хотя по-украински читает его почти дословно верно.
    /// Поэтому отменить замену она может только уверенным «это наш язык»; сомнение
    /// в её собственном ответе — не довод оставить кусок как есть.
    public static func keepsOwn(verdict: String, confidence: Float, own: Language) -> Bool {
        verdict == own.rawValue && confidence >= certainty
    }

    /// Годится ли чтение соседа на замену. Пустая расшифровка — провал декодера, а не
    /// ответ: большая модель на коротком отрезке молча отдаёт пустоту, и менять на неё
    /// живую речь нельзя ни при каком вердикте.
    public static func usable(_ reading: String) -> Bool {
        !reading.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}
