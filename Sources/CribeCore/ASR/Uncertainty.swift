import Foundation

/// Кусок диктовки, в котором распознаватель шёл неуверенно несколько слов подряд.
public struct UncertainRun: Equatable, Sendable {
    /// Слова куска в порядке речи.
    public let words: [String]

    public init(words: [String]) {
        self.words = words
    }

    /// Кусок строкой — тем же, чем он приехал человеку.
    public var text: String { words.joined(separator: " ") }
}

/// Поиск сломанных кусков по уверенности распознавания.
///
/// **Откуда правило.** Порог по ОДНОМУ слову не работает, и это замерено: верные слова
/// садятся ровно в тот же диапазон, что и ошибки. `staging` — 0.434, `11` — 0.514,
/// `мс` — 0.475, `Telegram` — 0.644, и всё это верно распознано. Ошибочные «пришёл» (0.338)
/// и «проверте» (0.583) от них по числу неотличимы. Причины у низких чисел на верных словах
/// понятные: первое слово диктовки всегда около 0.70 (модели не на что опереться), числа
/// и единицы неоднозначны в записи, а термины низкие оттого, что словарная подсказка сама
/// сталкивает латиницу с кириллицей — уверенность делится между двумя написаниями.
///
/// Работает другое: сломанные слова идут ЦЕПОЧКОЙ. Whisper не ошибается в одном слове —
/// он декодирует окно одним языковым токеном и потому гробит фразу целиком. На чистой речи
/// неуверенные слова стоят поодиночке, между ними соседи с 0.95–0.99.
///
/// **Замер** (двенадцать надиктованных владельцем записей, 2026-08-09): шесть срабатываний,
/// все настоящие, ноль ложных. Молчит и на технической записи, где четыре слова поодиночке
/// ниже порога. Пропускает короткие ошибки в одно-два слова — это устройство правила,
/// а не настройка.
public enum Uncertainty {

    /// Ниже этого слово считается неуверенным. Замер: худшая цепочка на ВЕРНОМ тексте —
    /// два слова (0.594 и 0.408), лучшая на сломанном — три (0.685, 0.655, 0.480).
    public static let shaky: Float = 0.72

    /// Короче этого цепочка не считается поломкой.
    ///
    /// Было три, стало четыре — по двум ложным тревогам на живой диктовке владельца
    /// (2026-08-09, тот же день). Обе цепочки были ровно в три слова, обе на верном тексте:
    /// «Да, уведомление видел» (0.579, 0.664, 0.514) и «видел", показал: "Сверьте,»
    /// (0.353, 0.486, 0.608). Вторая — важнее первой: диктовка там длинная, уверенных слов
    /// полно, а просела модель НЕ на словах, а на пунктуации — где ставить кавычки
    /// и двоеточия. То есть низкая уверенность метит сомнение в оформлении так же,
    /// как сомнение в услышанном, и отличить их по самому числу нельзя.
    ///
    /// Все настоящие поломки замера были длиной 4, 5 и 7 слов, обе ложные — ровно 3.
    /// Ценой одной потерянной находки (цепочка из трёх на записи 12) правило перестало
    /// врать. Для предупреждения это верный размен: то, что кричит попусту, перестают
    /// читать — и тогда пропускают и настоящее.
    ///
    /// Числа снова подобраны по тем же записям, на которых мерились. Это вторая подгонка
    /// на одном наборе; правило работает, но доказанным его считать нельзя.
    public static let minimumLength = 4

    /// Сколько уверенных слов должно остаться ВНЕ цепочки, чтобы она считалась куском,
    /// а не всей диктовкой. Без этого короткая фраза целиком уходит в «цепочку» — ровно
    /// так и вышло на «Да, уведомление видел», где уверенных слов не было ни одного.
    static let confidentOutside = 2

    /// Длиннее этого кусок в предупреждении обрезается: капсула маленькая, а человеку нужен
    /// адрес, а не пересказ. Первых слов хватает, чтобы найти место глазами.
    static let quotedLimit = 42

    /// Что сказать человеку. `nil` — молчим.
    ///
    /// Всегда с адресом. Безадресное «фраза перечитана» этой работы не делает: искать,
    /// куда смотреть, человеку всё равно приходится самому, а найденная гладкая фраза
    /// опаснее явного мусора — её принимают на веру вместе с потерянным отрицанием.
    ///
    /// Когда сверка соседним языком фразу УЖЕ перечитала, называем её НОВЫЙ вид: старых
    /// слов в тексте не осталось, и искать по ним было бы нечего.
    public static func alarm(runs: [UncertainRun], reread: [String]) -> String? {
        let places = reread.isEmpty ? runs.map(\.text) : reread
        guard let first = places.first else { return nil }
        let tail = places.count > 1 ? " и ещё \(places.count - 1)" : ""
        return "сверьте: «\(quoted(first))»\(tail)"
    }

    static func quoted(_ text: String) -> String {
        guard text.count > quotedLimit else { return text }
        return text.prefix(quotedLimit).trimmingCharacters(in: .whitespaces) + "…"
    }

    /// Сломанные куски в порядке речи. Пусто — значит ломаться нечему: ни предупреждения,
    /// ни дорогой сверки соседним языком.
    public static func runs(in words: [WordProbe]) -> [UncertainRun] {
        // Сломанный кусок узнаётся только на фоне целого текста. Нет фона — нет и вывода:
        // короткая фраза, просевшая целиком, это не поломка, а просто короткая фраза.
        guard words.filter({ $0.probability >= shaky }).count >= confidentOutside else { return [] }

        var runs: [UncertainRun] = []
        var current: [String] = []
        for word in words {
            if word.probability < shaky {
                current.append(word.word)
                continue
            }
            if current.count >= minimumLength { runs.append(UncertainRun(words: current)) }
            current = []
        }
        if current.count >= minimumLength { runs.append(UncertainRun(words: current)) }
        return runs
    }
}
