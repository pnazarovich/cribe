import Foundation

/// Одна растущая строка из перекрывающихся проходов по хвосту записи.
///
/// Предпросмотр перечитывает последние 12 с заново каждые ~0,9 с (см.
/// `DictationController.livePreviewSeconds`), поэтому ни один проход не продолжает
/// предыдущий: слева слова выпадают из окна, справа прибавляются, а середину Parakeet
/// перечитывает целиком и волен расслышать её иначе, поставить другую запятую и другую
/// заглавную. Показывать проход как есть — это и есть «рывками»: строка то удлиняется,
/// то укорачивается, а прочитанные слова переписываются под взглядом.
///
/// Свежий проход прикладывается к показанному по якорю — нескольким последним словам —
/// и дальше делает две вещи сразу: дописывает то, что стоит за якорем, и **переписывает
/// перекрытие своим написанием**. Второе важнее, чем кажется: каждый следующий проход
/// слышит те же слова с бо́льшим контекстом справа и потому слышит их лучше. Обрывок «верс»
/// становится «Vercel», ослышка чинится сама собой, а запятая и точка доезжают до слова,
/// которое уже проехало полстроки.
///
/// Правило «показанное слово не меняется» тут было, и оно же держало в строке весь мусор
/// первого прохода. Порядок слов при этом не трогается никогда: меняется написание, а не
/// состав, — иначе лента поехала бы назад.
///
/// Без UI и без контроллера намеренно: правило с числами внутри обязано проверяться
/// тестами, а поднимать ради него запись с моделью значит проверять не то.
public struct LiveTranscript: Sendable, Equatable {

    /// Насколько похожими должны быть перекрывающиеся куски, чтобы считать их одним и тем же
    /// местом речи.
    ///
    /// Не «дословно»: дословного совпадения тут не бывает по построению. Проходы идут по
    /// одному и тому же звуку, и следующий слышит его лучше — обрывок становится словом,
    /// приезжает запятая, чинится ослышка. Раньше выравнивание искало точный якорь из
    /// нескольких слов подряд, и ломалось оно ровно там, где правка и случалась: стоило
    /// поменяться слову, по которому выравниваемся, — и склейка объявляла «не сошлось».
    ///
    /// Половина — и вдобавок совпасть обязано не меньше `minimumOverlap` слов. Одной доли
    /// мало: на коротком перекрытии она скачет ступенями (три слова из пяти — это уже 0,6),
    /// и порог получался бы то строгим, то дырявым в зависимости от длины.
    static let matchRatio = 0.5

    /// Короче этого перекрытие не рассматриваем, и на перекрытии подлиннее столько же слов
    /// обязано совпасть дословно: два случайно совпавших служебных слова найдутся где угодно.
    static let minimumOverlap = 3

    /// Насколько близко к концу прохода обязан стоять якорь.
    ///
    /// Проходы приходят раз в ~1,4 с (период 0,9 плюс сам проход), за это время человек
    /// успевает сказать три-четыре слова. Значит истинное перекрытие кончается почти
    /// у самого конца прохода, а совпадение дальше от конца — это тот же оборот, сказанный
    /// раньше в том же окне. Без этой границы склейка вписывала бы всё, что между
    /// вхождениями, второй раз: перекрытие соседних проходов — это 11 секунд речи,
    /// то есть два-три десятка слов, и «пара лишних слов» тут не бывает.
    ///
    /// Публичная: тем же числом проверяет себя бегущая строка в панели, когда считает,
    /// на сколько уехать. Разъедься эти два числа — лента поехала бы на путь, которого
    /// склейка не проходила.
    public static let maxTail = 8

    /// Сколько проходов подряд вправе не сойтись, прежде чем строку продолжают вслепую.
    ///
    /// Не сошлось — значит показанного в окне уже нет: человек молчал дольше окна. Но то же
    /// самое бывает и когда перекрытие расслышано до неузнаваемости, а отличить их нечем:
    /// таймкодов Parakeet не даёт (см. шапку `ParakeetEngine`). Поэтому первые разы строку
    /// просто НЕ трогаем — замершая строка честнее выдуманной, — и только когда не сходится
    /// третий раз подряд (это уже больше четырёх секунд), дописываем то, что пришло.
    ///
    /// Именно ДОПИСЫВАЕМ, а не заменяем. Замена целиком тут и была тем, на что жаловались:
    /// «после паузы текст отъезжает назад». Строка прижата правым краем, и подмена всего
    /// содержимого читается как откат — а речь назад не идёт никогда. Цена монотонности —
    /// изредка повторённое слово; она заведомо меньше.
    static let staleAfter = 3

    /// Слова, которые уже показаны, в порядке речи.
    private var shown: [String] = []
    /// Сколько проходов подряд не сошлись с показанным.
    private var missed = 0

    public init() {}

    /// То, что показывает капсула.
    public var text: String { shown.joined(separator: " ") }

    /// Сколько слов уже собрано. По нему решают, пора ли показывать строку вообще.
    public var wordCount: Int { shown.count }

    /// Принимает очередной проход по хвосту записи.
    public mutating func absorb(_ pass: String) {
        let fresh = Self.words(in: pass)
        // Пустой проход — это не «сказанное отменяется», а окно, в которое попала одна
        // тишина. Гасить на нём строку нельзя: капсула сменила бы её на волну и через
        // 0,9 с вернула обратно — самый заметный рывок из всех, какие тут бывают.
        guard !fresh.isEmpty else { return }
        guard !shown.isEmpty else {
            shown = fresh
            settle()
            return
        }

        // Показанного слишком мало, чтобы из него вышло перекрытие: заменяем целиком.
        // До порога в четыре слова строка ещё никому не показана, терять нечего.
        guard shown.count >= Self.minimumOverlap else {
            shown = fresh
            missed = 0
            settle()
            return
        }

        // Ищем, каким куском своего начала свежий проход ложится на конец показанного.
        if let cut = Self.join(shown: shown, fresh: fresh) {
            adopt(fresh, upTo: cut)
            append(fresh[cut...])
            return
        }

        // Ни одного общего слова с показанным — человек молчал дольше окна, и в окне
        // осталась только новая фраза. Это НЕ «не сошлось»: продолжать тут честно, и
        // дописать её — единственный способ не дёрнуть строку.
        //
        // Раньше такой проход считался промахом: строка замирала на два прохода, а третьим
        // подменялась целиком — и уже прочитанное отъезжало назад на ровном месте.
        // Спутать это со «сбилось распознавание» нельзя: перекрытие соседних окон — это
        // одиннадцать секунд речи, и расслышать их до последнего слова иначе невозможно.
        if Self.disjoint(shown: shown, fresh: fresh) {
            append(fresh[...])
            return
        }

        missed += 1
        guard missed >= Self.staleAfter else { return }
        // Продолжаем вслепую: срезаем у свежего прохода тот кусок начала, который дословно
        // совпал с концом показанного, и дописываем остальное. Совпадения нет — дописываем
        // целиком: значит это и правда новая речь.
        append(fresh[Self.overlap(shown: shown, fresh: fresh)...])
    }

    /// Длина наибольшего конца показанного, дословно совпавшего с началом свежего прохода.
    static func overlap(shown: [String], fresh: [String]) -> Int {
        let old = keys(shown)
        let new = keys(fresh)
        for length in stride(from: min(old.count, new.count), through: 1, by: -1)
        where Array(old.suffix(length)) == Array(new.prefix(length)) {
            return length
        }
        return 0
    }

    /// Нет ли у показанного и свежего прохода ни одного общего слова.
    static func disjoint(shown: [String], fresh: [String]) -> Bool {
        let old = Set(keys(shown))
        return !keys(fresh).contains(where: old.contains)
    }

    /// Переписывает перекрытие написанием свежего прохода.
    ///
    /// `fresh[0..<cut]` — это ровно те же слова, что стоят в конце показанного: якорь для
    /// того и искали. Значит их можно подменить одно к одному, не трогая ни порядка,
    /// ни количества. Меняются при этом заглавные, запятые и сами слова там, где модель
    /// расслышала лучше, — а лента от этого не едет: правый край на месте.
    private mutating func adopt(_ fresh: [String], upTo cut: Int) {
        guard cut > 0, cut <= shown.count else { return }
        shown.replaceSubrange((shown.count - cut)..., with: fresh[0..<cut])
    }

    /// Дописываем не больше, чем человек успевает сказать за промежуток между проходами.
    ///
    /// Из трёх мест, откуда сюда приходят, стык известен только одному: `join` обрезает
    /// хвост сам, и он короче `maxTail` по построению. Два других — продолжение после паузы
    /// и слепое продолжение после трёх промахов — несут ВЕСЬ проход: десять секунд речи,
    /// два-три десятка слов, под тысячу точек пути при окне ленты в двести. Ленте такое
    /// показать нечем: она либо летит через всю строку, либо стоит, пока догоняет. Ровно
    /// это владелец и описал словами «всё пропало, и потом вся строка проехала мимо».
    ///
    /// Берём хвост, а не начало: середина потеряна теми же промахами, что привели сюда,
    /// а человеку в бегущей строке нужно последнее сказанное. Полный текст диктовки
    /// собирается не здесь и от этой обрезки не страдает.
    private mutating func append(_ tail: ArraySlice<String>) {
        missed = 0
        shown.append(contentsOf: tail.suffix(Self.maxTail))
        settle()
    }

    /// Строка НЕ обрезается слева, хотя показывают из неё десяток слов.
    ///
    /// Обрезка тут была, и она молча ломала ход ленты. Лента считает, на сколько ей ехать,
    /// по приросту числа слов; а когда слева отрезали столько же, сколько дописали справа,
    /// прирост выходил нулевым — лента стояла, а текст менялся кадром. Случалось это ровно
    /// на быстрой речи, когда строка упиралась в потолок, и выглядело как прыжок.
    ///
    /// Хранить всю диктовку ничего не стоит: это сотни коротких строк, а показывает
    /// ровно столько, сколько влезает, сама лента (`LiveTicker.tapeWords`).

    /// Приводит строку в вид, в котором её показывают: снимает выдуманный знак конца фразы
    /// и обрезает лишнее слева.
    ///
    /// Последнее слово прохода стоит на границе окна: для модели там кончилась речь, и она
    /// ставит точку или вопросительный знак. Через проход выясняется, что человек просто
    /// продолжал говорить, — но слово уже показано, а показанное не меняется. Так в строке
    /// и появлялась точка через каждые три-четыре слова, ровно по числу проходов. Настоящую
    /// пунктуацию расставит чистка на готовом тексте; здесь она заведомо выдуманная.
    private mutating func settle() {
        if let last = shown.last, let clean = Self.withoutSentenceEnd(last) {
            shown[shown.count - 1] = clean
        }
    }

    /// Слово без завершающего знака конца фразы — или nil, если снимать нечего.
    /// Запятую не трогаем: она стоит внутри фразы и границей окна не выдумывается.
    static func withoutSentenceEnd(_ word: String) -> String? {
        let ends: Set<Character> = [".", "?", "!", "…", ";", ":"]
        var trimmed = Substring(word)
        while let last = trimmed.last, ends.contains(last) { trimmed = trimmed.dropLast() }
        guard trimmed.count != word.count, !trimmed.isEmpty else { return nil }
        return String(trimmed)
    }


    static func words(in text: String) -> [String] {
        text.split(whereSeparator: \.isWhitespace)
            .map(String.init)
            // Одинокое тире словом не считаем: показывать нечего, а якорем оно было бы
            // пустым и совпало бы с любым другим таким же.
            .filter { !key($0).isEmpty }
    }

    static func keys(_ words: some Sequence<String>) -> [String] { words.map(key) }

    /// Нормализованное слово: регистр и знаки ставит сама модель и на разных проходах
    /// ставит по-разному — «дела» и «Дела?» одно слово. «ё»/«е» — по той же причине.
    static func key(_ word: String) -> String {
        word.lowercased()
            .replacingOccurrences(of: "ё", with: "е")
            .filter { $0.isLetter || $0.isNumber }
    }

    /// Сколько первых слов свежего прохода накрывают конец показанного, или nil, если
    /// сойтись не удалось.
    ///
    /// Перебираем длины перекрытия от большего к меньшему и берём первую, где совпало
    /// достаточно слов. Длинное перекрытие сильнее короткого: чем оно длиннее, тем меньше
    /// шансов, что это случайное совпадение служебных слов.
    static func join(shown: [String], fresh: [String]) -> Int? {
        let old = keys(shown)
        let new = keys(fresh)
        // Хвост после стыка не может быть длиннее `maxTail`: за период человек столько
        // и не успевает сказать, а стык, оставляющий больше, сел не туда.
        let shortest = max(Self.minimumOverlap, new.count - Self.maxTail)
        let longest = min(old.count, new.count)
        guard shortest <= longest else { return nil }

        for cut in stride(from: longest, through: shortest, by: -1) {
            let tail = old.suffix(cut)
            let head = new.prefix(cut)
            let same = zip(tail, head).count { $0 == $1 }
            // На коротком перекрытии требовать три совпадения нельзя: в самом начале
            // диктовки строка ещё из четырёх слов, и одно из них — обрубок правого края.
            // Тогда хватит и «все, кроме одного».
            guard same >= min(Self.minimumOverlap, cut - 1) else { continue }
            if Double(same) / Double(cut) >= Self.matchRatio { return cut }
        }
        return nil
    }
}
